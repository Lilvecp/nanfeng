"""Builds results/REPORT.md from results/before.json and results/after.json."""

import json
from collections import OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(label: str) -> dict:
    return json.loads((HERE / "results" / f"{label}.json").read_text())


def main() -> None:
    before, after = load("before"), load("after")
    b = {r["id"]: r for r in before["results"]}
    cats: OrderedDict[str, list[dict]] = OrderedDict()
    for r in after["results"]:
        cats.setdefault(r["category"], []).append(r)

    n = len(after["results"])
    sb = sum(r["stopped"] for r in before["results"])
    sa = sum(r["stopped"] for r in after["results"])
    lines = [
        "# Red team results (r4-06)",
        "",
        f"Generated by `report.py`. **Before** = `{before['ref']}` (placeholder policy, no guard). "
        f"**After** = `{after['ref']}`. OTP mode: `{after['otp_mode']}`. "
        "Each attack runs on a freshly reset sandbox and is judged by outcome (did the attacker's goal happen?).",
        "",
        f"**{sb}/{n} stopped before → {sa}/{n} stopped after** "
        f"({round(100 * sb / n)}% → {round(100 * sa / n)}%).",
        "",
        "| Category | Attacks | Before | After |",
        "|----------|---------|--------|-------|",
    ]
    for cat, rows in cats.items():
        lines.append(f"| {cat} | {len(rows)} | {sum(b[r['id']]['stopped'] for r in rows)} | "
                     f"{sum(r['stopped'] for r in rows)} |")
    lines += ["", "## Every attack", "", "| Id | Attack | Before | After | Evidence (after) |",
              "|----|--------|--------|-------|------------------|"]
    for rows in cats.values():
        for r in rows:
            ev = r["evidence"].replace("|", "/")[:110]
            lines.append(f"| {r['id']} | {r['name']} | {'✅' if b[r['id']]['stopped'] else '❌'} | "
                         f"{'✅' if r['stopped'] else '❌'} | {ev} |")
    fails = [r for r in after["results"] if not r["stopped"]]
    lines += ["", "## Still open", ""]
    lines += [f"- **{r['id']}** {r['name']}: {r['evidence']}" for r in fails] or ["- None"]
    (HERE / "results" / "REPORT.md").write_text("\n".join(lines) + "\n")
    print(f"{sb}/{n} -> {sa}/{n}; wrote results/REPORT.md")


if __name__ == "__main__":
    main()
